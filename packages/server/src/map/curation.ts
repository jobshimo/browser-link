export interface WrapUpDeps {
  session: AgentSession;
  /** Origins to report on in step 1. */
  origins: readonly string[];
  /** What the agent typed (session and process), for rule 7. */
  typedValues: readonly string[];
  validateSteps?: (steps: unknown[]) => string | null;
  /** Stores one feedback entry (the activity DB); called after the commit. */
  recordFeedback?: (item: FeedbackItem) => void;
  applyOptions?: ApplyOptions;
}

export interface WrapUpResult {
  step: 2;
  applied: AppliedItem[];
  rejected: Rejection[];
  /** Feedback entries that passed the rules but could not be stored. */
  errors?: string[];
}

/** Candidates named by `ids` (`o<outcome id>`), computed on their app's
 * current build. */
function candidatesFor(
  db: Database.Database,
  ids: readonly string[],
): Map<string, PitfallCandidate> {
  const out = new Map<string, PitfallCandidate>();
  const appIds = new Set<number>();
  for (const id of ids) {
    const m = /^o(\d+)$/.exec(id);
    if (!m) continue;
    const row = db
      .prepare('SELECT app_id FROM selector_outcomes WHERE id = ?')
      .get(Number(m[1])) as { app_id: number } | undefined;
    if (row) appIds.add(row.app_id);
  }
  for (const appId of appIds) {
    for (const c of pitfallCandidates(db, appId, currentAppBuild(db, appId))) out.set(c.id, c);
  }
  return out;
}

/**
 * `browser.wrap_up`: step 1 without a body, step 2 with one. Step 2 resets
 * the session's pending counter once its transaction committed.
 */
export function runWrapUp(
  db: Database.Database,
  args: unknown,
  deps: WrapUpDeps,
): WrapUpReport | WrapUpResult {
  if (!isCurationBody(args)) {
    return wrapUpReport(db, { origins: deps.origins, session: deps.session });
  }
  const body = parseCurationBody(args);
  const ids = [...(body.readers?.keep?.map((k) => k.id) ?? []), ...(body.readers?.drop ?? [])];
  const readers = new Map<number, ReaderRow>();
  for (const id of ids) {
    const r = getReader(db, id);
    if (r) readers.set(id, r);
  }
  const namesInUse = new Map<number, Set<string>>();
  for (const appId of new Set([...readers.values()].map((r) => r.app_id))) {
    const names = db
      .prepare(
        `SELECT name FROM js_readers WHERE app_id = ? AND status = 'kept' AND name IS NOT NULL`,
      )
      .all(appId) as { name: string }[];
    namesInUse.set(appId, new Set(names.map((n) => n.name)));
  }
  const plan = validateCuration(body, {
    readers,
    namesInUse,
    flows: deps.session.flows,
    candidates: candidatesFor(db, body.pitfalls?.confirm ?? []),
    typedValues: deps.typedValues,
    ...(deps.validateSteps ? { validateSteps: deps.validateSteps } : {}),
  });
  const applied = applyCuration(db, plan, deps.applyOptions);
  deps.session.pendingWrapUp = 0;
  const errors: string[] = [];
  plan.feedback.forEach((fb, i) => {
    if (!deps.recordFeedback) {
      errors.push(`feedback[${i}]: feedback storage is not available in this build`);
      return;
    }
    try {
      deps.recordFeedback(fb);
      applied.push({ item: `feedback[${i}]`, action: 'saved' });
    } catch (err) {
      errors.push(`feedback[${i}]: ${err instanceof Error ? err.message : String(err)}`);
    }
  });
  return { step: 2, applied, rejected: plan.rejected, ...(errors.length > 0 ? { errors } : {}) };
}
