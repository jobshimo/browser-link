export interface WrapUpSelector {
  action: string;
  target: string;
  url_pattern: string;
  ok_n: number;
  fail_n: number;
  last_reason: string | null;
}

export interface WrapUpApp {
  origin: string;
  app_key: string | null;
  build: string | null;
  readers: WrapUpReader[];
  flows_run: WrapUpFlow[];
  selectors: WrapUpSelector[];
  friction: Record<string, number>;
  pitfall_candidates: { id: string; sentence: string }[];
  /** Reserved: tool-shape anomalies the server may detect later. */
  feedback_candidates: never[];
}

export interface WrapUpReport {
  step: 1;
  apps: WrapUpApp[];
  /** Items left out to stay under `WRAP_UP_MAX_BYTES`; decide what is
   * shown and call again to see them. */
  omitted?: number;
}

function preview(expression: string): string {
  return expression.length > EXPRESSION_PREVIEW
    ? `${expression.slice(0, EXPRESSION_PREVIEW - 1)}…`
    : expression;
}

function appReport(db: Database.Database, origin: string, session: AgentSession): WrapUpApp | null {
  const app = winnerApp(db, origin);
  const flows = session.flows.filter((f) => f.origin === origin && f.kept === null);
  if (!app && flows.length === 0) return null;
  const build = app ? currentAppBuild(db, app.id) : null;
  const readers: WrapUpReader[] = app
    ? (
        db
          .prepare(
            `SELECT id FROM js_readers WHERE app_id = ? AND status = 'pending' ORDER BY id DESC`,
          )
          .all(app.id) as { id: number }[]
      )
        .map((r) => getReader(db, r.id))
        .filter((r): r is ReaderRow => r !== null)
        .map((r) => ({
          id: r.id,
          expression: preview(r.expression),
          kind: r.kind,
          flags: r.flags,
          ok_n: r.ok_n,
          fail_n: r.fail_n,
          result_bytes_avg: r.result_bytes_avg,
          ...(r.name ? { name: r.name } : {}),
        }))
    : [];
  const touched: OutcomeRow[] = app
    ? (db
        .prepare(
          `SELECT * FROM selector_outcomes
           WHERE app_id = ? AND (last_ok_at >= ? OR last_fail_at >= ?)
           ORDER BY MAX(COALESCE(last_ok_at, ''), COALESCE(last_fail_at, '')) DESC, id DESC`,
        )
        .all(app.id, session.startedAt, session.startedAt) as OutcomeRow[])
    : [];
  const friction: Record<string, number> = {};
  for (const row of touched) {
    if (
      row.last_reason !== null &&
      row.last_fail_at !== null &&
      row.last_fail_at >= session.startedAt
    ) {
      friction[row.last_reason] = (friction[row.last_reason] ?? 0) + 1;
    }
  }
  return {
    origin,
    app_key: app?.app_key ?? null,
    build,
    readers,
    flows_run: flows.map((f) => ({
      session_index: f.session_index,
      name: f.name,
      saved_name: f.saved_name,
      steps: f.steps.length,
      stopped_by: f.stopped_by,
      ok: f.ok,
    })),
    selectors: touched.slice(0, MAX_SELECTORS_PER_APP).map((r) => ({
      action: r.action,
      target: r.target,
      url_pattern: r.url_pattern,
      ok_n: r.ok_n,
      fail_n: r.fail_n,
      last_reason: r.last_reason,
    })),
    friction,
    pitfall_candidates: app
      ? pitfallCandidates(db, app.id, build).map((c) => ({ id: c.id, sentence: c.sentence }))
      : [],
    feedback_candidates: [],
  };
}

function bytes(value: unknown): number {
  return Buffer.byteLength(JSON.stringify(value));
}

/** Lists cut first when the report is over the cap, in this order. */
const TRIM_ORDER = ['selectors', 'readers', 'flows_run', 'pitfall_candidates'] as const;

/**
 * Step 1: what this session left to decide, per app of `origins` (the
 * session's origins and the connected tabs'), cut from the tail to fit
 * `WRAP_UP_MAX_BYTES`. Read-only.
 */
export function wrapUpReport(
  db: Database.Database,
  input: { origins: readonly string[]; session: AgentSession },
): WrapUpReport {
  const apps = [...new Set(input.origins)]
    .map((origin) => appReport(db, origin, input.session))
    .filter((a): a is WrapUpApp => a !== null);
  const report: WrapUpReport = { step: 1, apps };
  let omitted = 0;
  while (bytes(report) > WRAP_UP_MAX_BYTES) {
    let cut = false;
    for (const list of TRIM_ORDER) {
      for (let i = apps.length - 1; i >= 0 && !cut; i -= 1) {
        const items = apps[i][list] as unknown[];
        if (items.length > 0) {
          items.pop();
          cut = true;
        }
      }
      if (cut) break;
    }
    if (!cut) {
      if (apps.length === 0) break;
      apps.pop();
    }
    omitted += 1;
    report.omitted = omitted;
  }
  return report;
}

