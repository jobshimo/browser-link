/**
 * `browser.wrap_up`: the agent's curation step (knowledge-loop S9, S10).
 *
 * WHY
 * ---
 * The map records everything automatically (outcomes, the JS registry), but
 * only the agent knows which of those records are worth keeping under a
 * name. Before it answers the user it calls `wrap_up` twice:
 *
 *   1. without a body: what this session left pending, per app, ≤ 2 KB;
 *   2. with its decisions: validated here against the eight curation rules
 *      and applied in ONE transaction, so a crash midway leaves the map as it
 *      was. Anything not decided stays `pending` and is offered again.
 *
 * THE EIGHT RULES (the core states them; this module enforces them)
 * -----------------------------------------------------------------
 *   R1 only what worked enters knowledge (`ok_n ≥ 1`, last outcome ok);
 *   R2 a reader is kept only if reusable without this task's data: literals
 *      that are data become `<PLACEHOLDER>` templates;
 *   R3 never credentials, tokens, cookies, storage or personal data; a
 *      mutation is never kept as a reader;
 *   R4 names say what is returned: kebab-case, ≤ 40 chars, no leading verb;
 *   R5 one-offs are dropped by default (informational: a named one-off may
 *      be kept);
 *   R6 a pitfall is one verifiable sentence generated by the server from
 *      repeated structural failures, never free text, ≤ 200 chars;
 *   R7 nothing about the user: nothing the agent typed this session;
 *   R8 in doubt, drop: `drop` is always accepted and wins over `keep`.
 *
 * The server never rewrites an expression: a kept reader stores its
 * template next to the original, which stays as recorded.
 */

/** Serialized cap of the step-1 report, in UTF-8 bytes. */
export const WRAP_UP_MAX_BYTES = 2048;
/** Expressions are shown truncated to this many characters in step 1. */
export const EXPRESSION_PREVIEW = 160;
/** Upper bound on a pitfall sentence (rule 6). */
export const MAX_PITFALL_TEXT = 200;
/** Upper bound on each feedback text field. */
export const MAX_FEEDBACK_TEXT = 500;
/** Selectors listed per app in step 1, most recent first. */
const MAX_SELECTORS_PER_APP = 20;
/** Characters of a target quoted in a pitfall sentence. */
const MAX_TARGET_IN_SENTENCE = 100;

/* ------------------------------------------------------ placeholders ---- */

const PLACEHOLDER = /<([A-Z][A-Z0-9_]*)>/g;

/** The distinct `<PLACEHOLDER>` names in `text`, in order of appearance. */
export function placeholdersOf(text: string): string[] {
  return [...new Set([...text.matchAll(PLACEHOLDER)].map((m) => m[1]))];
}

/** Escape a value so it can sit inside a '…', "…" or `…` JS string literal. */
function escapeForLiteral(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/`/g, '\\`')
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

function valueText(values: Readonly<Record<string, unknown>>, name: string): string | null {
  const v = values[name];
  if (typeof v === 'string') return v;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return null;
}

/**
 * Fill every `<PLACEHOLDER>` of `template` from `values`. `js` escapes each
 * value for a string literal (a placeholder belongs inside one); `text`
 * inserts it as is. Throws naming every placeholder without a value.
 */
export function fillPlaceholders(
  template: string,
  values: Readonly<Record<string, unknown>>,
  mode: 'js' | 'text',
): string {
  const missing = placeholdersOf(template).filter((n) => valueText(values, n) === null);
  if (missing.length > 0) {
    throw new Error(`missing value for ${missing.map((n) => `<${n}>`).join(', ')}`);
  }
  return template.replace(PLACEHOLDER, (_m, name: string) => {
    const text = valueText(values, name) as string;
    return mode === 'js' ? escapeForLiteral(text) : text;
  });
}

/** Fill the placeholders of every string inside flow steps (deep copy). */
export function fillStepPlaceholders(
  steps: unknown,
  values: Readonly<Record<string, unknown>>,
): unknown {
  const missing = new Set<string>();
  const visit = (node: unknown): void => {
    if (typeof node === 'string') {
      for (const n of placeholdersOf(node)) if (valueText(values, n) === null) missing.add(n);
    } else if (Array.isArray(node)) node.forEach(visit);
    else if (typeof node === 'object' && node !== null) Object.values(node).forEach(visit);
  };
  visit(steps);
  if (missing.size > 0) {
    throw new Error(`missing value for ${[...missing].map((n) => `<${n}>`).join(', ')}`);
  }
  const fill = (node: unknown): unknown => {
    if (typeof node === 'string') return fillPlaceholders(node, values, 'text');
    if (Array.isArray(node)) return node.map(fill);
    if (typeof node === 'object' && node !== null) {
      return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, fill(v)]));
    }
    return node;
  };
  return fill(steps);
}

/* ------------------------------------------------------------ body ---- */

export interface FeedbackItem {
  tool: string;
  observed: string;
  expected: string;
}

export interface CurationBody {
  readers?: { keep?: { id: number; name: string; template?: string }[]; drop?: number[] };
  flows?: { keep?: { session_index: number; name: string }[] };
  pitfalls?: { confirm?: string[]; drop?: string[] };
  feedback?: FeedbackItem[];
}

const BODY_KEYS = ['readers', 'flows', 'pitfalls', 'feedback'] as const;

/** True when `args` carries decisions (step 2); no body or `{}` is step 1. */
export function isCurationBody(args: unknown): boolean {
  return typeof args === 'object' && args !== null && Object.keys(args).length > 0;
}

function fail(message: string): never {
  throw new Error(`browser.wrap_up: ${message}`);
}

function obj(value: unknown, path: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    fail(`${path} must be an object`);
  }
  return value as Record<string, unknown>;
}

function arr(value: unknown, path: string): unknown[] {
  if (!Array.isArray(value)) fail(`${path} must be an array`);
  return value;
}

function int(value: unknown, path: string): number {
  if (typeof value !== 'number' || !Number.isInteger(value) || value < 0) {
    fail(`${path} must be an integer`);
  }
  return value;
}

function str(value: unknown, path: string, max?: number): string {
  if (typeof value !== 'string' || value.length === 0) fail(`${path} must be a non-empty string`);
  if (max !== undefined && value.length > max) fail(`${path} is longer than ${max} characters`);
  return value;
}

function onlyKeys(o: Record<string, unknown>, keys: readonly string[], path: string): void {
  for (const k of Object.keys(o)) {
    if (!keys.includes(k)) fail(`unknown field "${path ? `${path}.` : ''}${k}"`);
  }
}

/** Check the shape of a step-2 body. Throws naming the first bad field;
 * nothing is applied when it throws. */
export function parseCurationBody(raw: unknown): CurationBody {
  if (raw === undefined || raw === null) return {};
  const o = obj(raw, 'the body');
  onlyKeys(o, BODY_KEYS, '');
  const body: CurationBody = {};
  if (o.readers !== undefined) {
    const r = obj(o.readers, 'readers');
    onlyKeys(r, ['keep', 'drop'], 'readers');
    body.readers = {};
    if (r.keep !== undefined) {
      body.readers.keep = arr(r.keep, 'readers.keep').map((item, i) => {
        const p = `readers.keep[${i}]`;
        const k = obj(item, p);
        onlyKeys(k, ['id', 'name', 'template'], p);
        return {
          id: int(k.id, `${p}.id`),
          name: str(k.name, `${p}.name`),
          ...(k.template !== undefined ? { template: str(k.template, `${p}.template`) } : {}),
        };
      });
    }
    if (r.drop !== undefined) {
      body.readers.drop = arr(r.drop, 'readers.drop').map((v, i) => int(v, `readers.drop[${i}]`));
    }
  }
  if (o.flows !== undefined) {
    const f = obj(o.flows, 'flows');
    onlyKeys(f, ['keep'], 'flows');
    body.flows = {};
    if (f.keep !== undefined) {
      body.flows.keep = arr(f.keep, 'flows.keep').map((item, i) => {
        const p = `flows.keep[${i}]`;
        const k = obj(item, p);
        onlyKeys(k, ['id', 'session_index', 'name'], p);
        const index = k.session_index !== undefined ? k.session_index : k.id;
        return { session_index: int(index, `${p}.session_index`), name: str(k.name, `${p}.name`) };
      });
    }
  }
  if (o.pitfalls !== undefined) {
    const p = obj(o.pitfalls, 'pitfalls');
    onlyKeys(p, ['confirm', 'drop'], 'pitfalls');
    body.pitfalls = {};
    for (const key of ['confirm', 'drop'] as const) {
      if (p[key] !== undefined) {
        body.pitfalls[key] = arr(p[key], `pitfalls.${key}`).map((v, i) =>
          str(v, `pitfalls.${key}[${i}]`),
        );
      }
    }
  }
  if (o.feedback !== undefined) {
    body.feedback = arr(o.feedback, 'feedback').map((item, i) => {
      const p = `feedback[${i}]`;
      const k = obj(item, p);
      onlyKeys(k, ['tool', 'observed', 'expected'], p);
      return {
        tool: str(k.tool, `${p}.tool`, MAX_FEEDBACK_TEXT),
        observed: str(k.observed, `${p}.observed`, MAX_FEEDBACK_TEXT),
        expected: str(k.expected, `${p}.expected`, MAX_FEEDBACK_TEXT),
      };
    });
  }
  return body;
}

/* ------------------------------------------------------ validation ---- */

/** A pitfall the server generated from repeated structural failures. */
export interface PitfallCandidate {
  /** `o<selector_outcomes.id>`: what `pitfalls.confirm` names. */
  id: string;
  app_id: number;
  action: string;
  target: string;
  reason: string;
  n: number;
  build: string | null;
  /** Insight key it is saved under. */
  key: string;
  /** The template sentence; the only text a confirmed pitfall carries. */
  sentence: string;
}

export interface CurationContext {
  /** Every reader the body names, by id. */
  readers: ReadonlyMap<number, ReaderRow>;
  /** Names of kept readers per app. */
  namesInUse: ReadonlyMap<number, ReadonlySet<string>>;
  /** The session's flow runs. */
  flows: readonly SessionFlowRecord[];
  /** The candidates the body may confirm, by id. */
  candidates: ReadonlyMap<string, PitfallCandidate>;
  /** What the agent typed (rule 7). */
  typedValues: readonly string[];
  /** Flow-step validator (`validateFlowSteps`), injected to keep this
   * module free of the dispatcher. Returns an error or null. */
  validateSteps?: (steps: unknown[]) => string | null;
}

export interface Rejection {
  item: string;
  rule: number;
  reason: string;
}

export interface CurationPlan {
  keepReaders: { id: number; app_id: number; name: string; template: string | null }[];
  dropReaders: number[];
  keepFlows: { record: SessionFlowRecord; name: string }[];
  confirmPitfalls: PitfallCandidate[];
  dropPitfalls: string[];
  feedback: FeedbackItem[];
  rejected: Rejection[];
}

/** Whether the last recorded outcome of a reader was ok. */
function lastOutcomeOk(r: ReaderRow): boolean {
  if (r.last_ok_at === null) return false;
  return r.last_fail_at === null || r.last_ok_at >= r.last_fail_at;
}

/** Why a reader cannot be kept under `name` with `template`, or null. */
function readerProblem(
  r: ReaderRow,
  name: string,
  template: string | null,
  ctx: CurationContext,
  claimed: Set<string>,
): Omit<Rejection, 'item'> | null {
  if (r.kind === 'mutation') {
    return { rule: 3, reason: 'a mutation is never kept as a reader' };
  }
  if (r.flags.includes('secret_shape') || hasSecretShape(r.expression)) {
    return { rule: 3, reason: 'the expression has a secret shape' };
  }
  if (r.ok_n < 1 || !lastOutcomeOk(r)) {
    return { rule: 1, reason: 'only what worked enters knowledge (ok_n ≥ 1, last outcome ok)' };
  }
  const nameProblem = readerNameProblem(name);
  if (nameProblem) return { rule: 4, reason: `name ${nameProblem}` };
  for (const text of [name, template ?? '', r.expression]) {
    if (containsTypedValue(text, ctx.typedValues)) {
      return { rule: 7, reason: 'contains something typed this session' };
    }
  }
  if (template !== null) {
    if (hasSecretShape(template)) return { rule: 3, reason: 'the template has a secret shape' };
    if (codeSkeleton(template) !== codeSkeleton(r.expression)) {
      return { rule: 2, reason: 'a template may differ from the expression only inside strings' };
    }
    if (analyzeExpression(template, []).kind !== 'reader') {
      return { rule: 3, reason: 'the template is a mutation' };
    }
    if (templateDataLiterals(template, ctx.typedValues).length > 0) {
      return {
        rule: 2,
        reason: 'a template literal still holds data outside its <PLACEHOLDER> tokens',
      };
    }
  }
  if (r.flags.includes('literal_data')) {
    if (template === null) {
      return { rule: 2, reason: 'literal_data: send a template with <PLACEHOLDER> tokens' };
    }
    if (placeholdersOf(template).length === 0) {
      return { rule: 2, reason: 'the template has no <PLACEHOLDER> token' };
    }
    const left = dataLiterals(r.expression, ctx.typedValues).filter((lit) =>
      template.includes(lit),
    );
    if (left.length > 0) return { rule: 2, reason: 'a data literal is still in the template' };
  }
  const inUse = ctx.namesInUse.get(r.app_id);
  const alreadyMine = r.status === 'kept' && r.name === name;
  if ((inUse?.has(name) && !alreadyMine) || claimed.has(`${r.app_id}:${name}`)) {
    return { rule: 4, reason: `name "${name}" is already used by another reader of this app` };
  }
  return null;
}

/**
 * Validate a parsed step-2 body against the eight rules. Pure. Every
 * rejection names its rule; `drop` is always accepted and wins over a
 * `keep` of the same id (rule 8).
 */
export function validateCuration(body: CurationBody, ctx: CurationContext): CurationPlan {
  const plan: CurationPlan = {
    keepReaders: [],
    dropReaders: [...new Set(body.readers?.drop ?? [])],
    keepFlows: [],
    confirmPitfalls: [],
    dropPitfalls: [...new Set(body.pitfalls?.drop ?? [])],
    feedback: [],
    rejected: [],
  };
  const dropped = new Set(plan.dropReaders);
  const claimed = new Set<string>();
  for (const keep of body.readers?.keep ?? []) {
    const item = `reader #${keep.id}`;
    if (dropped.has(keep.id)) {
      plan.rejected.push({ item, rule: 8, reason: 'also in drop: in doubt, drop' });
      continue;
    }
    const r = ctx.readers.get(keep.id);
    if (!r) {
      plan.rejected.push({ item, rule: 1, reason: 'no such reader' });
      continue;
    }
    const template = keep.template ?? null;
    const problem = readerProblem(r, keep.name, template, ctx, claimed);
    if (problem) {
      plan.rejected.push({ item, ...problem });
      continue;
    }
    claimed.add(`${r.app_id}:${keep.name}`);
    plan.keepReaders.push({ id: r.id, app_id: r.app_id, name: keep.name, template });
  }

  const flowNames = new Set<string>();
  for (const keep of body.flows?.keep ?? []) {
    const item = `flow ${keep.session_index}`;
    const record = ctx.flows.find((f) => f.session_index === keep.session_index);
    const reject = (rule: number, reason: string): void => {
      plan.rejected.push({ item, rule, reason });
    };
    if (!record) {
      reject(1, 'no such flow run in this session');
    } else if (record.kept !== null) {
      reject(1, `already saved as "${record.kept}"`);
    } else if (!record.ok) {
      reject(1, 'only a flow that worked is saved');
    } else if (record.origin === null) {
      reject(1, 'the app this flow ran on is unknown');
    } else if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(keep.name) || keep.name.length > 40) {
      reject(4, 'name must be kebab-case, at most 40 characters');
    } else if (
      containsTypedValue(keep.name, ctx.typedValues) ||
      containsTypedValue(JSON.stringify(record.steps), ctx.typedValues)
    ) {
      reject(7, 'contains something typed this session: use <PLACEHOLDER> values');
    } else if (flowNames.has(`${record.origin}:${keep.name}`)) {
      reject(4, `name "${keep.name}" is used twice`);
    } else {
      const stepsProblem = ctx.validateSteps?.(record.steps) ?? null;
      if (stepsProblem !== null) {
        reject(1, `steps no longer validate: ${stepsProblem}`);
      } else {
        flowNames.add(`${record.origin}:${keep.name}`);
        plan.keepFlows.push({ record, name: keep.name });
      }
    }
  }

  const droppedPitfalls = new Set(plan.dropPitfalls);
  for (const id of new Set(body.pitfalls?.confirm ?? [])) {
    const item = `pitfall ${id}`;
    if (droppedPitfalls.has(id)) {
      plan.rejected.push({ item, rule: 8, reason: 'also in drop: in doubt, drop' });
      continue;
    }
    const candidate = ctx.candidates.get(id);
    if (!candidate) {
      plan.rejected.push({ item, rule: 6, reason: 'only a server-generated candidate id' });
    } else if (candidate.sentence.length > MAX_PITFALL_TEXT) {
      plan.rejected.push({ item, rule: 6, reason: `longer than ${MAX_PITFALL_TEXT} characters` });
    } else if (containsTypedValue(candidate.sentence, ctx.typedValues)) {
      plan.rejected.push({ item, rule: 7, reason: 'contains something typed this session' });
    } else {
      plan.confirmPitfalls.push(candidate);
    }
  }

  (body.feedback ?? []).forEach((fb, i) => {
    const text = `${fb.tool}\n${fb.observed}\n${fb.expected}`;
    if (containsTypedValue(text, ctx.typedValues) || hasSecretValue(text)) {
      plan.rejected.push({
        item: `feedback[${i}]`,
        rule: containsTypedValue(text, ctx.typedValues) ? 7 : 3,
        reason: 'describe the tool, not the data',
      });
    } else {
      plan.feedback.push(fb);
    }
  });
  return plan;
}

/* ----------------------------------------------------------- apply ---- */

export interface AppliedItem {
  item: string;
  action: 'kept' | 'dropped' | 'saved' | 'confirmed';
  name?: string;
}

export interface ApplyOptions {
  /** Called after every write, inside the transaction. Tests throw from it
   * to prove a failure midway leaves the DB unchanged. */
  onStep?: (step: string) => void;
}

function appById(db: Database.Database, id: number): AppRow | null {
  return (db.prepare('SELECT * FROM apps WHERE id = ?').get(id) as AppRow | undefined) ?? null;
}

/**
 * Apply a validated plan in ONE transaction (feedback is not part of it: it
 * lives in another database and is written by the caller after the
 * commit). On a throw nothing is written. Kept flows are marked on their
 * session record only after the commit.
 */
export function applyCuration(
  db: Database.Database,
  plan: CurationPlan,
  opts: ApplyOptions = {},
): AppliedItem[] {
  const step = (label: string): void => opts.onStep?.(label);
  const applied = db.transaction((): AppliedItem[] => {
    const out: AppliedItem[] = [];
    for (const id of plan.dropReaders) {
      setReaderStatus(db, id, 'dropped');
      out.push({ item: `reader #${id}`, action: 'dropped' });
      step(`drop reader ${id}`);
    }
    for (const keep of plan.keepReaders) {
      setReaderStatus(db, keep.id, 'kept', keep.name);
      setReaderTemplate(db, keep.id, keep.template);
      out.push({ item: `reader #${keep.id}`, action: 'kept', name: keep.name });
      step(`keep reader ${keep.id}`);
    }
    for (const candidate of plan.confirmPitfalls) {
      const app = appById(db, candidate.app_id);
      if (!app) throw new Error(`app ${candidate.app_id} of pitfall ${candidate.id} is gone`);
      saveInsight({
        origin: app.origin,
        app_key: app.app_key,
        kind: 'pitfall',
        key: candidate.key,
        description: candidate.sentence,
      });
      out.push({ item: `pitfall ${candidate.id}`, action: 'confirmed', name: candidate.key });
      step(`confirm pitfall ${candidate.id}`);
    }
    for (const id of plan.dropPitfalls) out.push({ item: `pitfall ${id}`, action: 'dropped' });
    for (const keep of plan.keepFlows) {
      const origin = keep.record.origin as string;
      saveFlow({
        origin,
        app_key: winnerApp(db, origin)?.app_key ?? null,
        name: keep.name,
        steps: keep.record.steps,
      });
      out.push({ item: `flow ${keep.record.session_index}`, action: 'saved', name: keep.name });
      step(`save flow ${keep.record.session_index}`);
    }
    return out;
  })();
  for (const keep of plan.keepFlows) keep.record.kept = keep.name;
  return applied;
}

/* ---------------------------------------------------------- step 1 ---- */

interface OutcomeRow {
  id: number;
  app_id: number;
  url_pattern: string;
  target: string;
  action: string;
  ok_n: number;
  fail_n: number;
  last_reason: string | null;
  last_ok_at: string | null;
  last_fail_at: string | null;
  struct_fail_n: number;
}

function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function candidateOf(row: OutcomeRow, build: string | null): PitfallCandidate {
  const target =
    row.target.length > MAX_TARGET_IN_SENTENCE
      ? `${row.target.slice(0, MAX_TARGET_IN_SENTENCE - 1)}…`
      : row.target;
  const reason = row.last_reason ?? 'failed';
  const hash = createHash('sha256').update(`${row.action}\n${row.target}`).digest('hex');
  return {
    id: `o${row.id}`,
    app_id: row.app_id,
    action: row.action,
    target: row.target,
    reason,
    n: row.struct_fail_n,
    build,
    key: `learned-${row.action}-${slug(row.target).slice(0, 60)}-${hash.slice(0, 6)}`,
    sentence: `${row.action} on \`${target}\` was ${reason} ${row.struct_fail_n} times on build ${build ?? 'unknown'}`,
  };
}

/**
 * Pitfall candidates of an app: targets with ≥ 2 structural failures on
 * `build` since they last worked (the `failing` threshold), each phrased by
 * a fixed template. Candidates already confirmed (their key is saved) are
 * not offered again.
 */
export function pitfallCandidates(
  db: Database.Database,
  appId: number,
  build: string | null,
): PitfallCandidate[] {
  const rows = db
    .prepare(
      `SELECT * FROM selector_outcomes
       WHERE app_id = ? AND struct_fail_n >= ? AND struct_fail_build IS ?
       ORDER BY struct_fail_n DESC, id ASC`,
    )
    .all(appId, FAILING_THRESHOLD, build) as OutcomeRow[];
  const saved = new Set(
    (
      db.prepare(`SELECT key FROM insights WHERE app_id = ? AND kind = 'pitfall'`).all(appId) as {
        key: string;
      }[]
    ).map((r) => r.key),
  );
  return rows
    .filter((r) => countsAsStructural(r.last_reason))
    .map((r) => candidateOf(r, build))
    .filter((c) => !saved.has(c.key));
}

